import type { PropsWithChildren } from "react";

/**
 * Small line-icon set (Lucide paths) used across the app. Each icon is a thin
 * wrapper over a shared <svg> so call sites stay readable: `<TrashIcon />`
 * instead of a dozen lines of markup. Size/colour come from `className`
 * (defaults to h-4 w-4, currentColor).
 */

interface IconProps {
  className?: string;
}

function Icon({
  className = "h-4 w-4",
  children,
}: PropsWithChildren<IconProps>) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

